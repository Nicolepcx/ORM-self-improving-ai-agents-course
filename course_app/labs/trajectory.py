"""Minimal trajectory data model mirroring ART (`Trajectory`, `History`, `Choice`), used by the viewer."""

from dataclasses import dataclass, field
from typing import Dict, List, Optional


@dataclass
class Message:
    role: str
    content: Optional[str] = None
    is_choice: bool = False  # True = generated by the model (an ART `Choice`)
    tool_calls: List[Dict] = field(default_factory=list)  # [{"id", "name", "arguments"}]
    tool_call_id: Optional[str] = None
    branch: Optional[int] = None  # index of the additional history this message spawned / belongs to


@dataclass
class History:
    label: str
    note: str
    messages: List[Message]


@dataclass
class Trajectory:
    messages: List[Message]
    additional_histories: List[History]
    reward: float
    metrics: Dict


def system(text: str) -> Message:
    return Message("system", text)


def user(text: str, branch: Optional[int] = None) -> Message:
    return Message("user", text, branch=branch)


def tool(call_id: str, text: str) -> Message:
    return Message("tool", text, tool_call_id=call_id)


def choice(text: Optional[str] = None, tool_calls: Optional[List[Dict]] = None,
           branch: Optional[int] = None) -> Message:
    return Message("assistant", text, is_choice=True, tool_calls=tool_calls or [], branch=branch)


def from_openai_message(m: dict) -> Message:
    """Convert an OpenAI chat message dict (as sent to / returned by the API) into a viewer Message."""
    if m["role"] == "assistant":
        calls = [{"id": tc["id"], "name": tc["function"]["name"], "arguments": tc["function"]["arguments"]}
                 for tc in m.get("tool_calls") or []]
        return Message("assistant", m.get("content"), is_choice=True, tool_calls=calls)
    return Message(m["role"], m.get("content"), tool_call_id=m.get("tool_call_id"))
